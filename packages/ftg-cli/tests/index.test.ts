test('explicit request contracts emit separate typed payloads and reject read-only, unknown and malformed fields',async()=>{
  const root=await fixture();
  try{
    const body={type:'object',additionalProperties:false,required:['name','password','serverId'],properties:{
      name:{type:'string',minLength:2,maxLength:20},password:{type:'string',writeOnly:true,minLength:8},
      serverId:{type:'string',readOnly:true},quantity:{type:'integer',minimum:1},
      note:{type:['string','null']},contact:{type:'object',additionalProperties:false,required:['email'],properties:{email:{type:'string',format:'email'},created:{type:'string',readOnly:true}}}
    }};
    const doc=structuredClone(contract) as unknown as Record<string,unknown>;
    const paths=doc.paths as Record<string,Record<string,unknown>>;
    paths['/items']!.post={operationId:'CreateItem',requestBody:{required:true,content:{'application/json':{schema:body}}},responses:{'201':{description:'Created'}}};
    await writeFile(join(root,'openapi.json'),JSON.stringify(doc));
    await writeFile(join(root,'ftg.json'),JSON.stringify({openapi:'openapi.json',output:'generated',resources:[{name:'items',operationId:'ListItems',responsePath:['items']}],requests:[{name:'create-item',operationId:'CreateItem'}]}));
    await generate(join(root,'ftg.json'));
    const validators=createRequire(import.meta.url)(join(root,'generated','request-validators.gen.cjs'));
    const good={name:'Item',password:'synthetic',quantity:1,note:null,contact:{email:'example@example.invalid'}};
    const before=structuredClone(good);assert.equal(validators['create-item'](good),true);
    for(const bad of [{...good,name:'x'},{...good,password:undefined},{...good,serverId:'server-owned'},
      {...good,quantity:'1'},{...good,quantity:0},{...good,extra:'not-selected'},
      {...good,contact:{email:'invalid'}},{...good,contact:{...good.contact,created:'server-owned'}}])assert.equal(validators['create-item'](bad),false);
    assert.deepEqual(good,before);
    const types=await readFile(join(root,'generated','request-models.gen.ts'),'utf8');
    assert.match(types,/export type RequestModels/);assert.match(types,/"password": string/);assert.doesNotMatch(types,/serverId|created/);
    const metadata=await readFile(join(root,'generated','requests.gen.ts'),'utf8');assert.match(metadata,/"editable": true/);
    const reader=await import(pathToFileURL(join(root,'generated','read-models.gen.ts')).href);
    const writer=await import(pathToFileURL(join(root,'generated','request-models.gen.ts')).href);
    assert.throws(()=>reader.parseRead('constructor',{}),/INVALID_API_RESPONSE/);
    assert.throws(()=>writer.parseRequest('constructor',{}),/INVALID_API_REQUEST/);
    assert.deepEqual(writer.parseRequest('create-item',good),good);
    assert.deepEqual((await generate(join(root,'ftg.json'),{check:true})).changed,[]);
  }finally{await rm(root,{recursive:true,force:true});}
});
