test('JSON success status is explicit; 201 and 202 do not masquerade as 200 or grant form editability',async()=>{
  for(const status of ['201','202']){
    const root=await fixture();
    try{
      const doc=structuredClone(contract) as unknown as Record<string,unknown>;
      (doc.paths as Record<string,Record<string,unknown>>)['/items']!.post={operationId:'SubmitItem',responses:{[status]:{description:'Accepted',content:{'application/json':{schema:{type:'object',additionalProperties:false,required:['id'],properties:{id:{type:'string',format:'uuid'}}}}}}}};
      await writeFile(join(root,'openapi.json'),JSON.stringify(doc));
      const selection={name:'submission',operationId:'SubmitItem',responseStatus:status};
      await writeFile(join(root,'ftg.json'),JSON.stringify({openapi:'openapi.json',output:'generated',resources:[selection]}));
      await generate(join(root,'ftg.json'));
      const {parseRead}=await import(pathToFileURL(join(root,'generated','read-models.gen.ts')).href);
      assert.deepEqual(parseRead('submission',{id:'b50c40a4-fb7b-4ea1-926f-fc9e3df50d25'}),{id:'b50c40a4-fb7b-4ea1-926f-fc9e3df50d25'});
      assert.throws(()=>parseRead('submission',{id:'invalid'}),/INVALID_API_RESPONSE/);
      const resources=await readFile(join(root,'generated','resources.gen.ts'),'utf8');
      assert.match(resources,new RegExp('"responseStatus": "'+status+'"'));assert.doesNotMatch(resources,/"editable": true/);
      for(const bad of [{name:'submission',operationId:'SubmitItem'}, {...selection,responseStatus:'400'}]){
        await writeFile(join(root,'ftg.json'),JSON.stringify({openapi:'openapi.json',output:'generated',resources:[bad]}));
        await assert.rejects(generate(join(root,'ftg.json')),/MISSING_JSON_RESPONSE|UNSUPPORTED_JSON_SUCCESS_STATUS/);
      }
    }finally{await rm(root,{recursive:true,force:true});}
  }
});
