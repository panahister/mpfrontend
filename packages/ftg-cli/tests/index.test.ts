const contract = {
  openapi: '3.1.0',
  info: { title: 'Fixture', version: '1.0.0' },
  paths: {
    '/items': {
      get: {
        operationId: 'ListItems',
        responses: {
          '200': {
            description: 'Items',
            content: {
              'application/json': {
                schema: {
                  type: 'object',
                  required: ['items'],
                  properties: {
                    items: { type: 'array', items: { $ref: '#/components/schemas/Item' } },
                  },
                },
              },
            },
          },
        },
      },
    },
  },
  components: {
    schemas: {
      Item: {
        type: 'object',
        required: ['id', 'name'],
        properties: { id: { type: 'string', readOnly: true }, name: { type: 'string' } },
      },
    },
  },
};

async function fixture() {
  const root = await mkdtemp(join(tmpdir(), 'mpfrontend-ftg-'));
  // Standalone readers import only their declared Ajv runtime helpers, not the compiler.
  await symlink(fileURLToPath(new URL('../node_modules',import.meta.url)),join(root,'node_modules'),'dir');
  await writeFile(join(root, 'openapi.json'), JSON.stringify(contract));
  await writeFile(join(root, 'ftg.json'), JSON.stringify({
    openapi: 'openapi.json',
    output: 'generated',
    resources: [{ name: 'items', operationId: 'ListItems', responsePath: ['items'] }],
  }));
  return root;
}

test('generation is deterministic and check detects drift', async () => {
  const root = await fixture();
  try {
    const first = await generate(join(root, 'ftg.json'));
    assert.deepEqual(first.changed, ['resources.gen.ts', 'read-models.gen.ts', 'read-validators.gen.cjs', 'read-validators.gen.d.cts', 'requests.gen.ts', 'request-models.gen.ts', 'request-validators.gen.cjs', 'request-validators.gen.d.cts', 'generation-manifest.json']);
    assert.deepEqual((await generate(join(root, 'ftg.json'), { check: true })).changed, []);
    await writeFile(join(root, 'generated', 'resources.gen.ts'), '// @generated by FTG; edit authored overrides instead.\nchanged\n');
    await assert.rejects(generate(join(root, 'ftg.json'), { check: true }), (error: unknown) =>
      error instanceof InputError && error.exitCode === 3 && error.message === 'GENERATED_DRIFT');
    assert.match(await readFile(join(root, 'generated', 'generation-manifest.json'), 'utf8'), /"contractHash"/);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('generated full-response readers enforce constraints, formats and read-only direction without mutating data',async()=>{
  const root=await fixture();
  try{
    const constrained=structuredClone(contract);
    constrained.components.schemas.Item={type:'object',additionalProperties:false,required:['id','name','secret'],properties:{
      id:{type:'string',format:'uuid',readOnly:true},name:{type:'string',minLength:2,maxLength:20},
      secret:{type:'string',writeOnly:true},note:{type:['string','null']},
      tags:{type:'array',items:{type:'string'},maxItems:2},count:{type:'integer',minimum:1},
      occurredOnUtc:{type:'string',format:'date-time'}
    }} as never;
    await writeFile(join(root,'openapi.json'),JSON.stringify(constrained));
    await generate(join(root,'ftg.json'));
    const validators=createRequire(import.meta.url)(join(root,'generated','read-validators.gen.cjs'));
    const good={items:[{id:'b50c40a4-fb7b-4ea1-926f-fc9e3df50d25',name:'Readable',note:null,tags:['a'],count:1,occurredOnUtc:'2026-10-07T05:00:00Z'}]};
    const before=structuredClone(good);
    assert.equal(validators.items(good),true);
    for(const bad of [{items:[{...good.items[0],id:'not-uuid'}]},
      {items:[{...good.items[0],name:'x'}]}, {items:[{...good.items[0],secret:'never-return-this'}]},
      {items:[{...good.items[0],count:'1'}]}, {items:[{...good.items[0],count:0}]},
      {items:[{...good.items[0],tags:['a','b','c']}]}, {items:[{...good.items[0],extra:true}]},
      {items:[{...good.items[0],occurredOnUtc:'yesterday'}]}]){
      assert.equal(validators.items(bad),false);
    }
    assert.deepEqual(good,before);
    const types=await readFile(join(root,'generated','read-models.gen.ts'),'utf8');
    assert.match(types,/export type ReadModels/);assert.match(types,/readonly "items"/);
    assert.match(types,/"note"\?: string \| null/);assert.doesNotMatch(types,/"secret"/);
    const source=await readFile(join(root,'generated','read-validators.gen.cjs'),'utf8');
    assert.doesNotMatch(source,/new Function\(|\beval\(/);
    assert.deepEqual((await generate(join(root,'ftg.json'),{check:true})).changed,[]);
  }finally{await rm(root,{recursive:true,force:true});}
});

